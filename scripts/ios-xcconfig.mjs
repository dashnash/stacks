#!/usr/bin/env node
/**
 * Writes native/ios/Config/{Production,Staging}.xcconfig from stacks.config.json (and
 * native/ios/VERSION), so the iOS app's domains, bundle IDs and Google client IDs have one source.
 * `--check` fails if the committed files are out of date (CI, and the test in tools/app-conformance).
 *
 *   node scripts/ios-xcconfig.mjs [--check]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** iOS client `123-abc.apps.googleusercontent.com` → URL scheme `com.googleusercontent.apps.123-abc`. */
export const reversedClientId = (id) => (id ? id.replace(/\.apps\.googleusercontent\.com$/, '').replace(/^/, 'com.googleusercontent.apps.') : 'com.googleusercontent.apps.unset');

const covers = (outer, inner) => inner !== outer && inner.endsWith(`.${outer}`);

/** The xcconfig text for one environment. Values never contain "//" (xcconfig comments). */
export function xcconfig(config, envName, version) {
  const env = config.environments[envName];
  const native = env.native ?? {};
  if (!native.iosBundleId) throw new Error(`stacks.config.json: environments.${envName}.native.iosBundleId is required`);
  const others = Object.entries(config.environments)
    .filter(([name, e]) => name !== envName && covers(env.rootDomain, e.rootDomain))
    .map(([, e]) => e.rootDomain);
  const iosClient = (native.googleIosClientIds ?? [])[0] ?? '';
  const lines = {
    PRODUCT_BUNDLE_IDENTIFIER: native.iosBundleId,
    APP_DISPLAY_NAME: envName === 'production' ? 'DashyHQ' : 'DashyHQ Test',
    MARKETING_VERSION: version,
    STACKS_ROOT_DOMAIN: env.rootDomain,
    STACKS_OTHER_ROOTS: others.join(','),
    GOOGLE_SERVER_CLIENT_ID: env.googleClientId,
    GOOGLE_IOS_CLIENT_ID: iosClient,
    GOOGLE_REVERSED_CLIENT_ID: reversedClientId(iosClient),
    DEVELOPMENT_TEAM: native.appleTeamId ?? '',
  };
  for (const [k, v] of Object.entries(lines)) if (String(v).includes('//')) throw new Error(`${k} can't contain "//" in an xcconfig`);
  return [`// Generated by scripts/ios-xcconfig.mjs from stacks.config.json (${envName}). Don't edit: run it again.`, ...Object.entries(lines).map(([k, v]) => `${k} = ${v}`), ''].join('\n');
}

export function outputs() {
  const config = JSON.parse(readFileSync(join(root, 'stacks.config.json'), 'utf8'));
  const version = readFileSync(join(root, 'native/ios/VERSION'), 'utf8').trim();
  return {
    'native/ios/Config/Production.xcconfig': xcconfig(config, 'production', version),
    'native/ios/Config/Staging.xcconfig': xcconfig(config, 'staging', version),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [file, text] of Object.entries(outputs())) {
    const path = join(root, file);
    let current = null;
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // missing
    }
    if (current === text) continue;
    if (check) {
      console.error(`${file} is out of date: run node scripts/ios-xcconfig.mjs`);
      stale++;
    } else {
      writeFileSync(path, text);
      console.log(`wrote ${file}`);
    }
  }
  process.exit(stale ? 1 : 0);
}
